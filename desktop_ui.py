"""LinkScope layout and visual styles."""
import tkinter as tk
from tkinter import ttk


def build(app):
    root = app.root
    root.geometry('1060x840')
    root.minsize(960, 800)
    style = ttk.Style(root)
    style.theme_use('clam')
    bg, ink, muted, accent = '#f3f6f8', '#182c3a', '#506474', '#08756f'
    style.configure('.', font=('Segoe UI', 10), background=bg, foreground=ink)
    style.configure('TFrame', background=bg)
    style.configure('TLabel', background=bg)
    style.configure('Title.TLabel', font=('Segoe UI', 24, 'bold'))
    style.configure('Muted.TLabel', foreground=muted)
    style.configure('Section.TLabel', font=('Segoe UI', 11, 'bold'))
    style.configure('TButton', background='#e4ecef', borderwidth=0, padding=(14, 8))
    style.map('TButton', background=[('active', '#d4e1e7')])
    style.configure('Accent.TButton', background=accent, foreground='white')
    style.configure('Horizontal.TProgressbar', background=accent, troughcolor='#e4ecef', borderwidth=0)
    style.map('Accent.TButton', background=[('active', '#075d59'), ('disabled', '#a8b8ba')])
    style.configure('TEntry', padding=7, fieldbackground='white')
    style.configure('TCombobox', padding=6)
    style.configure('TNotebook', borderwidth=0)
    style.configure('TNotebook.Tab', padding=(18, 8), background='#e4ecef')
    style.map('TNotebook.Tab', background=[('selected', 'white')])
    style.configure('Treeview', background='white', fieldbackground='white', borderwidth=0, rowheight=34)
    style.configure('Treeview.Heading', background='#e4ecef', relief='flat', padding=8, font=('Segoe UI', 10, 'bold'))
    style.map('Treeview', background=[('selected', '#dcefeb')], foreground=[('selected', ink)])
    outer = ttk.Frame(root, padding=20)
    outer.pack(fill='both', expand=True)
    outer.columnconfigure(0, weight=1)
    outer.rowconfigure(4, weight=1)
    header = ttk.Frame(outer)
    header.grid(row=0, column=0, sticky='ew', pady=(0, 14))
    ttk.Label(header, text='LinkScope', style='Title.TLabel').pack(side='left')
    ttk.Label(header, text='URL & file reputation', style='Muted.TLabel').pack(side='left', padx=18)
    ttk.Label(header, textvariable=app.monitor_badge, style='Section.TLabel').pack(side='left', padx=12)
    ttk.Button(header, text='Try demo', command=app.demo).pack(side='right')
    tabs = ttk.Notebook(outer)
    tabs.grid(row=1, column=0, sticky='ew')
    screen, manual, settings = [ttk.Frame(tabs, padding=14) for _ in range(3)]
    for frame, title in [(screen, 'Screen monitor'), (manual, 'Check a link or file'), (settings, 'API settings')]:
        tabs.add(frame, text=title)
    controls = ttk.Frame(screen)
    controls.pack(fill='x')
    ttk.Button(controls, text='1. Select region', command=app.select_region).pack(side='left')
    app.start_button = ttk.Button(controls, text='2. Start monitoring', command=app.start, style='Accent.TButton')
    app.start_button.pack(side='left', padx=8)
    app.stop_button = ttk.Button(controls, text='Stop', command=app.stop, state='disabled')
    app.stop_button.pack(side='left')
    ttk.Label(controls, textvariable=app.region_label, style='Muted.TLabel').pack(side='left', padx=12)
    ttk.Checkbutton(screen, text='Automatically check detected links with VirusTotal', variable=app.auto,
                    command=app.change_auto).pack(anchor='w', pady=(12, 4))
    app.mode_hint = tk.StringVar()
    def update_hint(*_):
        app.mode_hint.set('Automatic checks ON · Public URLs are sent after you start and confirm.' if app.auto.get()
                          else 'Detection only · Links stay local until you choose to check them.')
    app.auto.trace_add('write', update_hint)
    update_hint()
    ttk.Label(screen, textvariable=app.mode_hint, style='Muted.TLabel').pack(anchor='w')
    ttk.Label(screen, text='Select the full https:// address with a little space around it. Two matching reads are required.', style='Muted.TLabel').pack(anchor='w', pady=(4, 0))
    ttk.Label(manual, text='Enter a full URL, SHA-256 hash, or choose a local file.').pack(anchor='w', pady=(0, 8))
    row = ttk.Frame(manual)
    row.pack(fill='x')
    ttk.Combobox(row, textvariable=app.kind, values=['URL', 'SHA-256', 'Local file'], state='readonly', width=12).pack(side='left')
    ttk.Entry(row, textvariable=app.value).pack(side='left', fill='x', expand=True, padx=8)
    ttk.Button(row, text='Browse', command=app.browse).pack(side='left')
    ttk.Button(row, text='Check now', command=app.manual, style='Accent.TButton').pack(side='left', padx=(8, 0))
    ttk.Label(manual, text='URLs are sent to VirusTotal. For files, only the SHA-256 hash is sent.', style='Muted.TLabel').pack(anchor='w', pady=8)
    ttk.Label(settings, text='VirusTotal API key · Stored only while LinkScope is open', style='Section.TLabel').pack(anchor='w')
    ttk.Entry(settings, textvariable=app.key, show='•', width=56).pack(anchor='w', pady=10)
    ttk.Label(settings, text='One lookup every 16 seconds. Up to 100 requests per session. Account limits also apply.', style='Muted.TLabel').pack(anchor='w')
    status = ttk.Frame(outer, padding=(0, 10))
    status.grid(row=2, column=0, sticky='ew')
    app.activity_bar = ttk.Progressbar(status, mode='indeterminate', length=100)
    app.activity_bar.pack(fill='x', pady=(0, 5))
    ttk.Label(status, textvariable=app.capture_activity, style='Section.TLabel').pack(anchor='w')
    ttk.Label(status, textvariable=app.request_activity, style='Muted.TLabel').pack(anchor='w')
    ttk.Label(status, textvariable=app.status, wraplength=820).pack(anchor='w')
    ttk.Label(status, textvariable=app.scan_status, style='Muted.TLabel', wraplength=820).pack(anchor='w', pady=(3, 0))
    bar = ttk.Frame(outer)
    bar.grid(row=3, column=0, sticky='ew', pady=(0, 6))
    ttk.Label(bar, text='Detected links & results', style='Section.TLabel').pack(side='left')
    app.check_selected_button = ttk.Button(bar, text='Check selected link', command=app.check_selected, state='disabled')
    app.check_selected_button.pack(side='right')
    app.submit_button = ttk.Button(bar, text='Submit URL for analysis', command=app.submit_selected, state='disabled')
    app.submit_button.pack(side='right', padx=8)
    box = ttk.Frame(outer)
    box.grid(row=4, column=0, sticky='nsew')
    app.table = ttk.Treeview(box, columns=('indicator', 'result', 'updated'), show='headings', height=3, selectmode='browse')
    app.table.heading('indicator', text='Link or file')
    app.table.heading('result', text='Check status')
    app.table.heading('updated', text='Time')
    app.table.column('updated', width=85, minwidth=85, stretch=False)
    app.table.column('indicator', width=500, minwidth=260)
    app.table.column('result', width=270, minwidth=240)
    app.table.pack(side='left', fill='both', expand=True)
    scroll = ttk.Scrollbar(box, command=app.table.yview)
    scroll.pack(side='right', fill='y')
    app.table.configure(yscrollcommand=scroll.set)
    app.table.bind('<<TreeviewSelect>>', app.details)
    details = ttk.Frame(outer)
    details.grid(row=5, column=0, sticky='ew', pady=(12, 8))
    app.detail = tk.Text(details, height=4, wrap='word', font=('Segoe UI', 10), bg='white', fg=ink,
                         relief='flat', padx=12, pady=10)
    app.detail.pack(side='left', fill='x', expand=True)
    scroll = ttk.Scrollbar(details, command=app.detail.yview)
    scroll.pack(side='right', fill='y')
    app.detail.configure(yscrollcommand=scroll.set)
    app.show_detail('No results yet\n\nSelect a region and start monitoring, check a link directly, or try the offline demo.\nDetection is local. Reputation checks use VirusTotal.')
    ttk.Label(outer, text='Reputation evidence, not a safety guarantee. No downloads or file uploads.', style='Muted.TLabel').grid(row=6, column=0, sticky='w')
